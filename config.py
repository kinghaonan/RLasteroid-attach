"""
小行星附着 RL 项目 —— 全局配置
小行星：中心引力场，R=500m，岩石行星 (ρ=2500 kg/m³)，无自转 (ω=0)
"""
import numpy as np

# ======================== 小行星物理参数 ========================
R_ASTEROID = 500.0              # 半径 [m]
RHO_ASTEROID = 2500.0           # 平均密度 [kg/m³]（岩石小行星典型值）
G = 6.67430e-11                 # 万有引力常数 [m³/(kg·s²)]

M_ASTEROID = RHO_ASTEROID * (4.0 / 3.0) * np.pi * R_ASTEROID**3      # 质量 ≈ 1.309×10¹² kg
MU = G * M_ASTEROID             # 引力参数 ≈ 87.37 m³/s²
G_SURFACE = MU / R_ASTEROID**2  # 表面重力加速度 ≈ 3.495×10⁻⁴ m/s²

# ======================== 航天器参数 ========================
M0 = 500.0                      # 初始质量 [kg]
M_DRY = 300.0                   # 干质量（含结构，燃料耗尽后的质量）[kg]
M_FUEL0 = M0 - M_DRY            # 初始燃料质量 = 200 kg
T_MAX = 200.0                   # 最大推力幅值 [N]（提高至200N以提供足够制动能力）
I_SP = 300.0                    # 比冲 [s]
G0 = 9.80665                    # 地球海平面重力加速度 [m/s²]
# 满推力燃料消耗率: ṁ = T_MAX / (I_SP * G0) ≈ 0.0170 kg/s
# 满推力最大燃烧时间: M_FUEL0 / 0.0170 ≈ 11765 s

# ======================== 环境参数 ========================
DT = 1.0                        # RK4 积分步长 [s]
MAX_STEPS = 2000                # 单回合最大步数
SUCCESS_DIST = 10.0             # 着陆成功距离阈值 [m]
SUCCESS_VEL = 0.5               # 着陆成功速度阈值 [m/s]（恢复严格标准）
ALTITUDE_MIN = 500.0            # 初始高度下限（距表面）[m]
ALTITUDE_MAX = 1500.0           # 初始高度上限（距表面）[m]
ESCAPE_RADIUS = 10.0 * R_ASTEROID  # 逃逸判定半径 [m]

# ======================== 奖励参数（密集奖励 + 进度引导） ========================
K_DIST = 3.0                    # 距离惩罚系数（|r - r_target| / R）
K_VEL = 0.3                     # 速度惩罚系数
K_PROGRESS = 10.0               # 接近进度奖励系数
K_DECEL = 5.0                   # 接近减速引导系数（越近越需要减速）
LAMBDA_FUEL = 0.01              # 燃料惩罚系数
GAMMA = 0.99                    # 折扣因子
R_SUCCESS = 5000.0              # 成功着陆奖励（巨大，引导学习）
R_CRASH = -500.0                # 撞击惩罚
R_ESCAPE = -500.0               # 逃逸惩罚
R_TIMEOUT = -200.0              # 超时惩罚
R_STEP = 0.0                    # 每步惩罚

# ======================== PPO 超参数 ========================
N_ENVS = 8                      # 并行环境数
N_STEPS = 2048                  # 每轮收集步数
BATCH_SIZE = 256                # 小批量大小
N_EPOCHS = 10                   # 每轮更新 epoch 数
LEARNING_RATE = 3e-4            # 学习率
ENT_COEF = 0.1                  # 高熵鼓励探索（纯RL轨迹优化）
VF_COEF = 0.5                   # 价值函数损失系数
CLIP_RANGE = 0.2                # PPO 剪切范围
GAE_LAMBDA = 0.95               # GAE λ 参数
TOTAL_TIMESTEPS = 2_000_000     # 总训练步数
EVAL_FREQ = 20000               # 评估频率
SAVE_FREQ = 50000               # 模型保存频率
